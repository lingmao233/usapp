def resolve_persona(preset: str, custom: str) -> str:
    """人格解析：自定义文本非空优先；否则查预设库，查不到回退默认观察员。"""
    custom = (custom or "").strip()
    if custom:
        return custom
    return PERSONAS.get(preset, PERSONAS[DEFAULT_PERSONA])

