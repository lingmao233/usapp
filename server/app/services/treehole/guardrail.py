"""树洞安全护栏（生成后检，⑤）：仅命中强烈自伤意愿时替换为干预话术。

故意做成确定性规则而非 LLM 判断：护栏是可解释、可回归的红线，不能随模型波动。
口径（交接文档§二）：普通情绪波动（"好累""好烦"）绝不打扰；只有明确指向
自伤/轻生的表达才触发。"好累""烦死了""气死我了"这类口语夸张不在名单内。
"""

# 强烈自伤意愿信号：明确指向结束生命/伤害自己的短语
_STRONG_SIGNALS = (
    "不想活", "活不下去", "活着没意思", "想死", "想结束", "自杀", "自残", "自伤",
    "轻生", "一了百了", "结束自己", "结束生命", "离开这个世界", "解脱算了",
)

# 口语夸张的缓冲：信号命中但这些前缀语境说明是情绪宣泄而非意愿（"烦得想死"≠想死）
_HYPERBOLE_HINTS = ("累得想死", "烦得想死", "气得想死", "忙得想死", "笑得想死", "吓死")

INTERVENTION_TEXT = (
    "听到你这样说，我真的很担心你。你此刻的痛苦是真实的，也值得被认真对待——"
    "但请相信，它不会永远这样。\n"
    "如果你正在经历伤害自己的念头，请现在就联系可以接住你的人：\n"
    "- 全国24小时心理援助热线：400-161-9995\n"
    "- 北京心理危机研究与干预中心：010-82951332\n"
    "- 紧急情况请拨打 120 / 110\n"
    "你不是一个人。等你准备好，我一直在这里。"
)


def is_strong_self_harm(message: str) -> bool:
    """仅强烈自伤意愿返回 True；口语夸张命中缓冲语境时不触发。"""
    text = (message or "").replace(" ", "")
    if not any(sig in text for sig in _STRONG_SIGNALS):
        return False
    if any(hint in text for hint in _HYPERBOLE_HINTS):
        return False
    return True
